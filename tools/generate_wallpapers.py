from pathlib import Path
import math,struct,zlib,hashlib,json
r=Path(__file__).resolve().parents[1];out=r/'launcher/app/src/main/assets/wallpapers';out.mkdir(parents=True,exist_ok=True)
W,H=1920,1080
scenes=[('golden-dunes',(17,23,42),(215,132,67),(240,195,118),0),('silver-peaks',(5,12,30),(75,100,141),(192,215,237),1),('turquoise-horizon',(4,22,48),(53,143,162),(157,229,220),2)]
def mix(a,b,t):return tuple(a[i]*(1-t)+b[i]*t for i in range(3))
def chunk(t,data):return struct.pack('>I',len(data))+t+data+struct.pack('>I',zlib.crc32(t+data)&0xffffffff)
manifest=[]
for name,top,horizon,light,kind in scenes:
 rows=bytearray()
 ridges=[]
 for layer in range(4):
  ridges.append([.58+layer*.09+(.05+layer*.012)*math.sin(x/W*(8+layer*2)+layer*1.8+kind)+.025*math.sin(x/W*23+layer) for x in range(W)])
 for y in range(H):
  rows.append(0);v=y/(H-1)
  for x in range(W):
   u=x/(W-1);c=mix(top,horizon,min(1,v/.70)**1.5)
   glow=math.exp(-((u-.72)**2/.04+(v-.43)**2/.05))*.34;c=mix(c,light,glow)
   if ((u-.72)*W/H)**2+(v-.43)**2<.0014:c=light
   if kind==1 and v<.48 and ((x*73856093)^(y*19349663))%5509==0:c=mix(c,light,.7)
   if kind==2 and v>.62:
    wave=.5+.5*math.sin(v*290+u*7)
    c=mix((9,45,63),(38,113,126),max(0,1-(v-.62)/.38))
    c=mix(c,light,wave*.075*math.exp(-((u-.72)/.20)**2))
   for layer in range(4):
    if v>ridges[layer][x]+(max(0,u-(.18+layer*.035))*2.0 if kind==2 else 0):
     shade=tuple(k*(.33-layer*.065) for k in horizon)
     c=mix(shade,top,.22)
   vignette=max(.58,1-.29*((u-.5)**2*2+(v-.47)**2))
   noise=((((x*1103515245+y*12345)&0xffff)/65535)-.5)*1.2
   rows.extend(max(0,min(255,round(k*vignette+noise))) for k in c)
 png=b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',W,H,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(rows,9))+chunk(b'IEND',b'')
 (out/(name+'.png')).write_bytes(png)
 manifest.append(dict(file=name+'.png',sha256=hashlib.sha256(png).hexdigest(),width=W,height=H,license='MIT',origin='Original procedural landscape generated by tools/generate_wallpapers.py; no external image inputs.'))
 print(name,len(png))
(r/'third_party/wallpaper-provenance.json').write_text(json.dumps(manifest,indent=2)+'\n')
